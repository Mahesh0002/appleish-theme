#!/usr/bin/env python3
"""GTK3 static base theme generator for Appleish.

Emits a GTK3 stylesheet entirely from ``tokens.json``.  Every number in the
output comes from a token; no magic numbers are inlined.  GTK3 does not
support CSS custom properties, ``@media``, ``transform``, ``filter``,
``overflow``, ``backdrop-filter`` or ``calc()`` — none of those appear.

Output goes to ``theme/gtk-3.0/gtk.css`` (dark) and
``theme/gtk-3.0/gtk-light.css`` (light).
"""

from __future__ import annotations

import argparse
from pathlib import Path

from tokens import ctx, font_rule

_HEX_OK = set()


def _validate_colour(value: str, where: str) -> str:
    """Ensure every colour is either rgba()/rgb() or a hex string."""
    if value.startswith("rgba(") or value.startswith("rgb("):
        return value
    import re
    if re.match(r"^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$", value):
        return value
    raise ValueError(f"{where}: unexpected colour value {value!r}")


