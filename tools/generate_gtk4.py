def write(mode: str = "dark", path: Path | str = Path("theme/gtk-4.0/gtk.css")) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    css = build(mode)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(css, encoding="utf-8")
    tmp.replace(path)
    return path


