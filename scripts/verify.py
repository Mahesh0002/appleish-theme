#!/usr/bin/env python3
"""Appleish verification suite — ``make verify``.

Runs every structural, token, spacing, typography, contrast and runtime
check in order.  Prints one ``[PASS]/[FAIL]/[SKIP] <name>`` line per check
and exits 1 if any check is FAIL.

Runtime CSS parsing (check 9) is optional: GTK3 files are parsed with
GTK 3 and GTK4 files with GTK 4 in subprocesses.  If a toolkit is not
installed, that check is reported as SKIP and does not fail the run.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

CSS_FILES = [
    ROOT / "theme/gtk-3.0/gtk.css",
    ROOT / "theme/gtk-3.0/gtk-light.css",
    ROOT / "theme/gtk-4.0/gtk.css",
    ROOT / "theme/gtk-4.0/gtk-light.css",
]
GTK3_FILES = CSS_FILES[:2]
GTK4_FILES = CSS_FILES[2:]

SPACING_ALLOWED = {0, 4, 8, 12, 16, 20, 24, 32, 40, 48, 56, 64}
RADIUS_ALLOWED = {0, 4, 8, 12, 16, 24, 9999}
GTK3_FORBIDDEN = ("--", "var(", "@media", "transform", "overflow:",
                  "calc(", "backdrop-filter")
GTK4_FORBIDDEN = ("transform", "overflow:", "calc(", "backdrop-filter", "filter:")

_results: list[tuple[str, str, str]] = []


def record(status: str, name: str, detail: str = "") -> None:
    _results.append((status, name, detail))


def run_check(name: str, fn) -> None:
    """Run ``fn``; PASS on return, FAIL on AssertionError/Exception."""
    try:
        fn()
    except AssertionError as exc:
        record("FAIL", name, str(exc))
    except Exception as exc:  # noqa: BLE001
        record("FAIL", name, f"{type(exc).__name__}: {exc}")
    else:
        record("PASS", name)


# ------------------------------------------------------------------ checks

def check_tokens() -> None:
    from tools.tokens import load
    raw = (ROOT / "tokens.json").read_text(encoding="utf-8")
    assert raw.strip(), "tokens.json is empty"
    dark = load("dark")["colors"]
    light = load("light")["colors"]
    assert set(dark) == set(light), (
        f"colour key mismatch: dark-only={sorted(set(dark) - set(light))}, "
        f"light-only={sorted(set(light) - set(dark))}"
    )
    try:
        load("bogus")
    except ValueError:
        pass
    else:
        raise AssertionError("load() accepted an invalid mode")


def check_files() -> None:
    for path in CSS_FILES:
        assert path.is_file(), f"missing {path.relative_to(ROOT)}"
        text = path.read_text(encoding="utf-8")
        assert text.strip(), f"empty {path.relative_to(ROOT)}"
        marker = ("generate_gtk3" if "gtk-3.0" in str(path) else "generate_gtk4")
        assert f"GENERATED by tools/{marker}.py" in text, (
            f"{path.relative_to(ROOT)} missing generated marker"
        )


def check_gtk3_constraints() -> None:
    for path in GTK3_FILES:
        text = path.read_text(encoding="utf-8")
        for bad in GTK3_FORBIDDEN:
            assert bad not in text, (
                f"{path.relative_to(ROOT)} contains forbidden token {bad!r}"
            )


def check_gtk4_vars() -> None:
    for path in GTK4_FILES:
        text = path.read_text(encoding="utf-8")
        for bad in GTK4_FORBIDDEN:
            assert bad not in text, (
                f"{path.relative_to(ROOT)} contains forbidden token {bad!r}"
            )
        assert ":root" in text, f"{path.relative_to(ROOT)} missing :root"
        m = re.search(r":root\s*\{(.*?)\}", text, re.S)
        assert m, f"{path.relative_to(ROOT)} :root block not parseable"
        defined = set(re.findall(r"(--[\w-]+)\s*:", m.group(1)))
        used = set(re.findall(r"var\((--[\w-]+)\)", text))
        missing = used - defined
        assert not missing, f"{path.relative_to(ROOT)} undefined vars: {sorted(missing)}"


def check_spacing() -> None:
    for path in CSS_FILES:
        text = path.read_text(encoding="utf-8")
        for m in re.finditer(r"(?:padding|margin|gap)(?:-\w+)?:\s*([^;]+);", text):
            for tok in m.group(1).split():
                if tok in ("0", "0px", "auto", "none") or tok.startswith("var("):
                    continue
                num = re.fullmatch(r"(-?\d+)px", tok)
                assert num and int(num.group(1)) in SPACING_ALLOWED, (
                    f"{path.relative_to(ROOT)}: off-grid spacing {m.group(0)!r}"
                )
        for m in re.finditer(r"border-radius:\s*([^;]+);", text):
            for tok in m.group(1).split():
                if tok in ("0", "0px", "50%") or tok.startswith("var("):
                    continue
                num = re.fullmatch(r"(\d+)px", tok)
                assert num and int(num.group(1)) in RADIUS_ALLOWED, (
                    f"{path.relative_to(ROOT)}: off-scale radius {m.group(0)!r}"
                )


def check_typography() -> None:
    gtk3 = (ROOT / "theme/gtk-3.0/gtk.css").read_text(encoding="utf-8")
    gtk4 = (ROOT / "theme/gtk-4.0/gtk.css").read_text(encoding="utf-8")
    for size in ("11px", "13px", "15px", "20px", "24px", "34px"):
        assert f"font-size: {size}" in gtk3, f"gtk3 missing font-size {size}"
    for token in ("caption: 11px", "footnote: 13px", "body: 15px",
                  "title3: 20px", "title2: 24px", "large_title: 34px"):
        assert f"--fs-{token}" in gtk4, f"gtk4 missing --fs-{token}"
    assert "font-feature-settings" in gtk3 and "'tnum'" in gtk3, (
        "gtk3 missing font-feature-settings tnum (GTK 3.24 has no font-variant-numeric)"
    )
    assert "tabular-nums" in gtk4, "gtk4 missing font-variant-numeric tabular-nums"
    for text, label in ((gtk3, "gtk3"), (gtk4, "gtk4")):
        generic = "font-size: 15px" if label == "gtk3" else "font-size: var(--fs-body)"
        assert generic in text, f"{label} missing 15px body rule"
        i_generic = text.index(generic)
        i_control = text.index("font-size: 13px", i_generic)
        assert i_control > i_generic, (
            f"{label}: control 13px rule must follow the generic 15px rule"
        )


def check_contrast() -> None:
    proc = subprocess.run(
        [sys.executable, str(ROOT / "tools/check_contrast.py")],
        cwd=str(ROOT), capture_output=True, text=True, timeout=120,
    )
    assert proc.returncode == 0, (
        "check_contrast.py failed:\n" + (proc.stdout + proc.stderr).strip()
    )


def check_metadata() -> None:
    index = ROOT / "theme/index.theme"
    assert index.is_file(), "theme/index.theme missing"
    text = index.read_text(encoding="utf-8")
    assert "Name=Appleish" in text, "index.theme missing Name=Appleish"
    assert "GtkTheme=Appleish" in text, "index.theme missing GtkTheme=Appleish"


def check_runtime_parse() -> None:
    """Optional: parse each CSS file with the matching GTK version."""
    gtk_version = {".css": None}  # placeholder, assigned per file below
    for path in CSS_FILES:
        version = "3.0" if path in GTK3_FILES else "4.0"
        code = (
            "import sys, gi;"
            f"gi.require_version('Gtk', '{version}');"
            "from gi.repository import Gtk;"
            "p = Gtk.CssProvider();"
            "p.load_from_data(open(sys.argv[1], 'rb').read())"
        )
        proc = subprocess.run(
            [sys.executable, "-c", code, str(path)],
            capture_output=True, text=True, timeout=120,
        )
        if proc.returncode == 0:
            continue
        err = (proc.stdout + proc.stderr).strip()
        unavailable = (
            "Namespace Gtk not available" in err
            or "cannot open display" in err
            or "Could not load required" in err
        )
        if unavailable:
            record("SKIP", "runtime parse (GTK unavailable)",
                   path.relative_to(ROOT).as_posix())
            return
        raise AssertionError(
            f"GTK {version} rejected {path.relative_to(ROOT)}:\n{err[:400]}"
        )


def check_docs() -> None:
    for rel in ("docs/spacing.md", "docs/DESIGN.md", "README.md"):
        assert (ROOT / rel).is_file(), f"missing {rel}"


# ------------------------------------------------------------------ main

def main() -> int:
    run_check("tokens.json parses + dark/light key parity", check_tokens)
    run_check("all four CSS files exist, non-empty, generated", check_files)
    run_check("GTK3 has no vars/@media/transform/filter/overflow/calc", check_gtk3_constraints)
    run_check("GTK4 :root vars defined and all var() resolved", check_gtk4_vars)
    run_check("spacing + radius audit (all four files)", check_spacing)
    run_check("typography scale present in both base files", check_typography)
    run_check("WCAG contrast (tools/check_contrast.py)", check_contrast)
    run_check("theme/index.theme metadata", check_metadata)
    run_check("runtime CSS parse (optional, skips if GTK absent)", check_runtime_parse)
    run_check("docs/spacing.md, docs/DESIGN.md, README.md exist", check_docs)

    failed = 0
    for status, name, detail in _results:
        line = f"[{status}] {name}"
        if detail:
            line += f" — {detail}"
        print(line)
        if status == "FAIL":
            failed += 1

    passed = sum(1 for r in _results if r[0] == "PASS")
    skipped = sum(1 for r in _results if r[0] == "SKIP")
    print(f"\n{passed} passed, {failed} failed, {skipped} skipped")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
